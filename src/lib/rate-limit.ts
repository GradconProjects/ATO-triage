/**
 * Small in-memory token bucket per key. Adequate for a single serverless instance; swap for
 * an Upstash/Redis limiter when running at scale. Auth endpoints are rate limited by Supabase.
 */
const buckets = new Map<string, { count: number; resetAt: number }>();

export function rateLimit(key: string, limit: number, windowMs: number): boolean {
  const now = Date.now();
  const b = buckets.get(key);
  if (!b || b.resetAt < now) {
    buckets.set(key, { count: 1, resetAt: now + windowMs });
    return true;
  }
  if (b.count >= limit) return false;
  b.count += 1;
  return true;
}
